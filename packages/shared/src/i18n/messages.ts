const catalogs: Record<Locale, Record<MessageKey, string>> = { en, de };

/** Looks up a message and fills `{placeholders}` from `params`. Unknown placeholders are left as-is. */
export function translate(locale: Locale, key: MessageKey, params: Record<string, string | number> = {}): string {
  return catalogs[locale][key].replace(/\{(\w+)\}/g, (match, name: string) =>
    name in params ? String(params[name]) : match,
  );
}
